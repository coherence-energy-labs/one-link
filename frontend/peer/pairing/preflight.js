  async function _waitForIdentity(maxMs) {
    const deadline = Date.now() + (maxMs || 8000);
    while (Date.now() < deadline) {
      if (state.rec) return state.rec;
      // v0.20.4: if boot already failed, abort the wait early
      // and let the caller surface the real error.
      if (state.boot_error_msg) return null;
      await new Promise((r) => setTimeout(r, 80));
    }
    return state.rec || null;
  }

  // v0.20.4 — preflight checks. Returns null if all good, or an
  // {pill, status} object describing the specific failure mode.
  // Most-common failure: insecure context. iOS Safari + most other
  // browsers gate Web Crypto Subtle to HTTPS or localhost; a phone
  // hitting http://<lan-ip>/peer can't generate Ed25519 keys at
  // all. The QR generated by v0.20.4+ daemons is https://, so this
  // should normally pass — but if the user got an http:// QR from
  // an older daemon or hand-typed the URL, we surface the real
  // reason instead of the generic "no identity" mystery.
  function _autopairPreflight() {
    if (!window.isSecureContext) {
      return {
        pill: "insecure",
        status:
          "This page is loaded over plain HTTP. Browsers block Web Crypto on " +
          "non-HTTPS LAN addresses, so identity generation can't run. Reopen " +
          "the QR on your laptop to get an https:// link, or open this on " +
          "the laptop's localhost.",
      };
    }
    if (!window.crypto || !crypto.subtle || !crypto.subtle.generateKey) {
      return {
        pill: "no web crypto",
        status:
          "Your browser doesn't expose the required Web Crypto operations. " +
          "Try an up-to-date browser. Release evidence currently covers " +
          "Chromium and Firefox, not WebKit/Safari.",
      };
    }
    if (!navigator.storage || !navigator.storage.getDirectory) {
      return {
        pill: "no opfs",
        status:
          "Your browser doesn't expose OPFS. The phone-as-peer architecture " +
          "needs persistent origin-private storage. Try an up-to-date browser; " +
          "Chromium and Firefox are tested, while WebKit/Safari remains a " +
          "release-qualification gap.",
      };
    }
    return null;
  }

