@pytest.mark.skipif(shutil.which("node") is None, reason="Node is required for lexical-scope execution")
def test_generated_services_cannot_capture_feature_state_or_leak_globals(tmp_path: Path) -> None:
    manifest = {"schema": 1, "template": "unused.html", "groups": []}
    for group_name, folder, factory, private_name in (
        ("owner", "main", "createOwnerProbe", "privateOwner"),
        ("calls", "calls", "createCallProbe", "privateCall"),
    ):
        (tmp_path / folder).mkdir(exist_ok=True)
        (tmp_path / "services").mkdir(exist_ok=True)
        factory_path = f"services/{folder}_probe.js"
        feature_path = f"{folder}/probe.js"
        (tmp_path / factory_path).write_text(f"function {factory}() {{ return typeof {private_name}; }}\n")
        (tmp_path / feature_path).write_text(
            f"const {private_name} = 42;\nglobalThis.{group_name}Probe = {factory}();\n"
        )
        manifest["groups"].append({"name": group_name, "modules": [
            {"path": factory_path, "kind": "service", "responsibility": "scope probe", "factory": factory},
            {"path": feature_path, "kind": "feature", "responsibility": "feature state probe"},
        ]})
    (tmp_path / "manifest.json").write_text(json.dumps(manifest) + "\n")
    scripts = builder.script_sources(tmp_path)
    program = (
        "const assert = require('node:assert/strict'); const vm = require('node:vm');\n"
        "const context = vm.createContext({});\n"
        f"vm.runInContext({json.dumps(scripts['owner'])}, context);\n"
        f"vm.runInContext({json.dumps(scripts['calls'])}, context);\n"
        "assert.equal(context.ownerProbe, 'undefined');\n"
        "assert.equal(context.callsProbe, 'undefined');\n"
        "assert.equal(context.createOwnerProbe, undefined);\n"
        "assert.equal(context.createCallProbe, undefined);\n"
    )
    result = subprocess.run(["node", "-e", program], capture_output=True, text=True, timeout=10)
    assert result.returncode == 0, result.stdout + result.stderr
