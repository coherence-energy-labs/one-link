"""Generated owner UI and isolated service integration contracts."""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

import pytest


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("build_owner_ui", ROOT / "scripts/build_owner_ui.py")
assert SPEC and SPEC.loader
builder = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(builder)


def test_committed_owner_ui_is_the_deterministic_build() -> None:
    expected = builder.build()
    assert expected == builder.OUTPUT.read_text(encoding="utf-8")
    assert builder.build() == expected
    assert "<!-- owner-ui:script " not in expected
    assert len(re.findall(r"<script>[\s\S]*?</script>", expected)) == 2
    assert expected.count('const PAGE_SOURCE_FINGERPRINT = "__ONE_LINK_SOURCE_FINGERPRINT__";') == 1
    assert "GENERATED by scripts/build_owner_ui.py" in expected


def test_stale_output_fails_check_without_rewriting(tmp_path: Path) -> None:
    output = tmp_path / "index.html"
    output.write_text("stale content\n", encoding="utf-8")
    command = [sys.executable, str(ROOT / "scripts/build_owner_ui.py"), "--output", str(output)]
    check = subprocess.run(command + ["--check"], capture_output=True, text=True, timeout=20)
    assert check.returncode == 1
    assert "stale" in check.stderr
    assert output.read_text(encoding="utf-8") == "stale content\n"
    built = subprocess.run(command, capture_output=True, text=True, timeout=20)
    assert built.returncode == 0, built.stderr
    assert output.read_bytes() == builder.OUTPUT.read_bytes()
    assert subprocess.run(command + ["--check"], capture_output=True, timeout=20).returncode == 0


@pytest.fixture
def source_copy(tmp_path: Path) -> Path:
    source = tmp_path / "owner_ui"
    shutil.copytree(builder.SOURCE, source)
    return source


@pytest.mark.parametrize("fault", ["duplicate", "missing", "unregistered", "factory", "marker", "fingerprint"])
def test_incomplete_or_ambiguous_source_set_cannot_build(source_copy: Path, fault: str) -> None:
    path = source_copy / "manifest.json"
    manifest = json.loads(path.read_text())
    modules = manifest["groups"][0]["modules"]
    if fault == "duplicate":
        modules.append(modules[0])
    elif fault == "missing":
        (source_copy / modules[0]["path"]).unlink()
    elif fault == "unregistered":
        (source_copy / "main/unregistered.js").write_text("function strayFeature() {}\n")
    elif fault == "factory":
        next(module for module in modules if module["kind"] == "service")["factory"] = "createMissingFactory"
    elif fault == "marker":
        template = source_copy / "index.template.html"
        template.write_text(template.read_text().replace("<!-- owner-ui:script calls -->", ""))
    else:
        version = source_copy / "main/version.js"
        version.write_text(version.read_text().replace(builder.FINGERPRINT, "stale-build"))
    path.write_text(json.dumps(manifest) + "\n")
    with pytest.raises(builder.BuildError):
        builder.build(source_copy)


def test_canonical_module_edit_is_embedded_once(source_copy: Path) -> None:
    module = source_copy / "main/transfer_facts.js"
    marker = "// transfer-module-rebuild-contract\n"
    module.write_text(module.read_text() + marker)
    result = builder.build(source_copy)
    assert result.count(marker) == 1
    assert "// owner-ui module: main/transfer_facts.js" in result


